// Shared types for Movement Dashboard components

export interface MorningBrief {
  greeting: string
  summary: string
  highlights: Array<{ icon: string; text: string }>
  quickActions: Array<{ label: string; action: string; icon: string }>
}

export interface Task {
  id: string
  title: string
  description: string
  priority: 'urgent' | 'high' | 'medium' | 'low'
  dueDate: string | null
  category: string
  status: string
}

export interface TasksResponse {
  tasks: Task[]
  totalTasks: number
  urgentCount: number
  byCategory: Record<string, number>
}

export interface StoryGap {
  project: string
  reason: string
  priority: string
}

export interface ArtOpportunity {
  title: string
  score: number
  type: string
  action: string
}

export interface CommandCenterOverview {
  stats: {
    stories: number
    storytellers: number
    contacts: number
    projects: number
    vignettes: number
    qaKnowledge: number
  }
  storyGaps: {
    urgent: StoryGap[]
    totalGaps: number
    urgentCount: number
  }
  artOpportunities: ArtOpportunity[]
  elderReview: {
    pending: number
    items: string[]
  }
  systemHealth: {
    overall: string
    services: Record<string, { status: string; url?: string; endpoints?: number }>
  }
}

export interface RelationshipContact {
  id: string
  name: string
  email?: string
  company?: string
  tier?: string
  lastContact?: string
  daysSince?: number
  relationship_strength?: number
}

export interface RelationshipsResponse {
  topContacts: RelationshipContact[]
  needsAttention: RelationshipContact[]
  recentActivity: Array<{
    type: string
    contact: string
    date: string
  }>
}

